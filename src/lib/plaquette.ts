export const matches = (code: string, m: Pick<MapLine, "prefixes" | "exclude" | "amort">) =>
  (m.prefixes.some((p) => code.startsWith(p)) && !(m.exclude ?? []).some((p) => code.startsWith(p))) || (m.amort ?? []).some((p) => code.startsWith(p));

/** Comptes de bilan/gestion (classes 1 à 8) qu'aucune ligne ne reprend. */
export const unmapped = (codes: string[]) => codes.filter((c) => /^[1-8]/.test(c) && !STATEMENT_MAP.some((m) => matches(c, m)));

